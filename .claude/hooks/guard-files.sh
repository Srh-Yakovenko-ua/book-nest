#!/usr/bin/env bash
set -u

INPUT="$(cat)"
TOOL="$(printf '%s' "$INPUT" | jq -r '.tool_name // empty')"
FILE="$(printf '%s' "$INPUT" | jq -r '.tool_input.file_path // .tool_input.notebook_path // .tool_input.path // empty')"
GLOB="$(printf '%s' "$INPUT" | jq -r '.tool_input.glob // empty')"
[ -z "$FILE" ] && [ -z "$GLOB" ] && exit 0

deny() {
  jq -n --arg r "$1" '{hookSpecificOutput:{hookEventName:"PreToolUse",permissionDecision:"deny",permissionDecisionReason:$r}}'
  exit 0
}

is_server_secret() {
  case "$1" in
    *.example) return 1 ;;
    *.env.prod | *.env.prod.* | *.env.dev | *.env.dev.* | *.env.stage | *.env.stage.*) return 0 ;;
    */.ssh/* | *id_ed25519* | *id_rsa* | *.pem) return 0 ;;
  esac
  return 1
}

for target in "$FILE" "$GLOB"; do
  [ -n "$target" ] && is_server_secret "$target" \
    && deny "That file holds live server credentials or keys. Ask the user for the specific value you need."
done

case "$TOOL" in
  Edit | Write | MultiEdit | NotebookEdit) ;;
  *) exit 0 ;;
esac

case "$FILE" in
  *.example) ;;
  */.env | */.env.*)
    deny "Real .env files hold secrets and are edited by the user. Put a new variable in the matching .env*.example and in config/env.ts (api) or lib/env.ts (web), then tell the user which value to set."
    ;;
esac

case "$FILE" in
  */apps/api/src/generated/*)
    deny "The Prisma client is generated. Edit apps/api/prisma/schema.prisma; the PostToolUse hook regenerates the client."
    ;;
  */apps/web/src/shared/api/generated/*)
    deny "The API client is generated by Orval. Change the backend contract (packages/shared + controller), then run pnpm gen:api in the main loop."
    ;;
  */pnpm-lock.yaml)
    deny "pnpm-lock.yaml is written by pnpm. Run the pnpm command that changes the dependency instead."
    ;;
  */apps/api/prisma/migrations/*/migration.sql)
    if git -C "$(dirname "$FILE")" ls-files --error-unmatch "$FILE" >/dev/null 2>&1; then
      deny "That migration is committed, and committed migrations are history: prod has already applied it. Create a NEW migration with pnpm --filter @app/api db:migrate --name <snake_case>. A freshly generated, untracked migration.sql stays editable so its spurious DROP INDEX lines can be stripped."
    fi
    ;;
esac
exit 0
